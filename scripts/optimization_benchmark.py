"""Before/after optimization benchmark, measured from Phoenix traces.

Optimization: MCP connection reuse. BEFORE = every MCP tool call opens a fresh stdio session (a new
server process) through MultiServerMCPClient.get_tools(); AFTER = one persistent MCP session per run
(TelecomMCP.session(), the production default).

For each mode the same contacts are run by `python -m src.cli run` in a separate process and Phoenix
project, spans are exported to traces/benchmark_<mode>.parquet, golden signals are computed with
scripts/golden_signals.compute() into reports/golden_signals_<before|after>.json, and
reports/optimization_note.md compares them. Correctness is checked: outcomes must be identical.

Run: python -m scripts.optimization_benchmark
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from datetime import datetime, timezone

from scripts.golden_signals import compute
from src.config import EVAL_REPORT_PATH, REPORTS_DIR, ROOT_DIR, TRACES_DIR

CONTACTS = ["CT-0001", "CT-0002", "CT-0005", "CT-0006", "CT-0014"]  # tool-heavy: account, billing, offers, tickets
MODES = {"before": "per-call", "after": "session"}


def run_mode(label: str, mode: str) -> dict:
    parquet = TRACES_DIR / f"benchmark_{label}.parquet"
    results = REPORTS_DIR / "benchmark" / f"{label}_results.jsonl"
    env = {**os.environ, "PHOENIX_PROJECT_NAME": f"retention-copilot-bench-{label}"}
    cmd = [sys.executable, "-m", "src.cli", "run", "--input", "data/sample_contacts.jsonl", "--only", *CONTACTS,
           "--auto-approve", "--no-llm", "--mcp-mode", mode, "--export-traces", "--export-path", str(parquet),
           "--results-path", str(results), "--logs-dir", str(ROOT_DIR / "logs" / "benchmark" / label)]
    print(f"[{label}] mcp-mode={mode}: {' '.join(cmd[2:6])} ...")
    proc = subprocess.run(cmd, cwd=ROOT_DIR, env=env, capture_output=True, text=True, timeout=1800)
    if proc.returncode != 0:
        raise SystemExit(f"{label} run failed:\n{proc.stdout[-1500:]}\n{proc.stderr[-1500:]}")
    gs = compute(parquet, EVAL_REPORT_PATH)
    gs["benchmark"] = {"label": label, "mcp_mode": mode, "contacts": CONTACTS, "results": str(results.relative_to(ROOT_DIR))}
    out = REPORTS_DIR / f"golden_signals_{label}.json"
    out.write_text(json.dumps(gs, indent=2, default=str) + "\n")
    outcomes = {json.loads(l)["contact_id"]: json.loads(l)["outcome"] for l in results.read_text().splitlines()}
    print(f"[{label}] -> {out.relative_to(ROOT_DIR)} | tool p50={gs['latency']['tool']['p50_ms']}ms "
          f"warm turn p50={gs['latency']['end_to_end_turn_warm']['p50_ms']}ms")
    return {"gs": gs, "outcomes": outcomes, "path": out}


def pct(before: float | None, after: float | None) -> str:
    if not before or after is None:
        return "n/a"
    return f"{(after - before) / before * 100:+.1f}%"


def row(name: str, b: float | None, a: float | None, unit: str = "ms") -> str:
    fmt = (lambda v: "n/a" if v is None else f"{v:,.1f} {unit}")
    return f"| {name} | {fmt(b)} | {fmt(a)} | {pct(b, a)} |"


def main() -> None:
    res = {label: run_mode(label, mode) for label, mode in MODES.items()}
    b, a = res["before"]["gs"], res["after"]["gs"]
    same = res["before"]["outcomes"] == res["after"]["outcomes"]
    lines = [
        "# Optimization note: MCP session reuse",
        "",
        f"Generated by `scripts/optimization_benchmark.py` at {datetime.now(timezone.utc).isoformat(timespec='seconds')}. "
        "Both columns are Phoenix-derived golden signals computed by `scripts/golden_signals.py` from spans exported "
        "by separate runs of the same contacts.",
        "",
        f"- **Before** (`--mcp-mode per-call`): every MCP tool call opens a new stdio session, i.e. spawns a new "
        f"MCP server process. Signals: `{res['before']['path'].relative_to(ROOT_DIR)}` <- `{b['sources']['spans']}`",
        f"- **After** (`--mcp-mode session`, default): one persistent MCP session per run (`TelecomMCP.session()`). "
        f"Signals: `{res['after']['path'].relative_to(ROOT_DIR)}` <- `{a['sources']['spans']}`",
        f"- Contacts: {', '.join(CONTACTS)} (account, billing, offer-eligibility and escalation tools), rules/templates "
        "engine (no Gemini calls), approvals auto-approved.",
        f"- Correctness: outcomes {'identical' if same else 'DIFFER'} across modes "
        f"({json.dumps(res['after']['outcomes'])}).",
        "",
        "| Signal | Before | After | Change |",
        "|---|---|---|---|",
        row("Tool span latency p50", b["latency"]["tool"]["p50_ms"], a["latency"]["tool"]["p50_ms"]),
        row("Tool span latency p95", b["latency"]["tool"]["p95_ms"], a["latency"]["tool"]["p95_ms"]),
        row("Tool span latency mean", b["latency"]["tool"]["mean_ms"], a["latency"]["tool"]["mean_ms"]),
        row("End-to-end turn p50 (warm)", b["latency"]["end_to_end_turn_warm"]["p50_ms"],
            a["latency"]["end_to_end_turn_warm"]["p50_ms"]),
        row("End-to-end turn p95 (warm)", b["latency"]["end_to_end_turn_warm"]["p95_ms"],
            a["latency"]["end_to_end_turn_warm"]["p95_ms"]),
        row("Acting span latency p95", b["latency"]["acting"]["p95_ms"], a["latency"]["acting"]["p95_ms"]),
        "",
        "Per MCP tool (p50):",
        "",
        "| Tool | Before | After | Change |",
        "|---|---|---|---|",
    ]
    for tool in sorted(set(b["latency"]["tool_by_name"]) | set(a["latency"]["tool_by_name"])):
        tb = b["latency"]["tool_by_name"].get(tool, {}).get("p50_ms")
        ta = a["latency"]["tool_by_name"].get(tool, {}).get("p50_ms")
        lines.append(row(f"`{tool}`", tb, ta))
    lines += [
        "",
        "`policy_rag` and `manage_memory` do not go through MCP, so they act as controls: they should not "
        "change between modes, and any large change there would point to noise rather than the optimization.",
        "",
        "Cost: both runs used no LLM calls, so token cost is $0 in both; the saving is latency and process "
        "churn (one MCP server process per run instead of one per tool call). The first turn of each run "
        "includes model loading and is excluded from the warm end-to-end figures "
        f"(cold first turn: before {b['latency']['cold_start_first_turn_ms']} ms, after "
        f"{a['latency']['cold_start_first_turn_ms']} ms).",
        "",
        "Decision: keep the persistent session as the default (`src/cli.py --mcp-mode session`); the per-call "
        "mode remains only as this benchmark's baseline.",
    ]
    note = REPORTS_DIR / "optimization_note.md"
    note.write_text("\n".join(lines) + "\n")
    print(f"-> {note.relative_to(ROOT_DIR)} (outcomes identical: {same})")


if __name__ == "__main__":
    main()
